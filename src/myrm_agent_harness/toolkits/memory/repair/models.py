"""[POS]: src/myrm_agent_harness/toolkits/memory/repair/models.py
[INPUT]: Core domain primitives and status enumerations for memory database health and pruning.
[OUTPUT]: Strongly typed IntegrityCheckReport, RepairReport, StalePrunePolicy, PruneSummary, and HealthMetric contracts.
"""

from enum import StrEnum

from pydantic import BaseModel, Field


class IntegrityStatus(StrEnum):
    """Database structural integrity health status."""

    HEALTHY = "healthy"
    DEGRADED = "degraded"
    CORRUPTED = "corrupted"
    REPAIRED = "repaired"


class RepairActionStatus(StrEnum):
    """Status result of a repair action operation."""

    SUCCESS = "success"
    PARTIAL = "partial"
    SKIPPED = "skipped"
    FAILED = "failed"


class MemoryRecordItem(BaseModel):
    """Memory entry representation evaluated during pruning."""

    id: str = Field(..., description="Unique identifier of the memory item")
    content: str = Field(..., description="Text content of the memory item")
    created_at_epoch: float = Field(..., description="Creation epoch timestamp in seconds")
    last_recalled_at_epoch: float = Field(..., description="Timestamp of the latest recall")
    recall_count: int = Field(default=0, description="Total recall counter")
    is_pinned: bool = Field(default=False, description="Flag indicating pinned/permanent preference")
    status: str = Field(default="active", description="Active or archived status")


class IntegrityCheckReport(BaseModel):
    """Diagnostic report generated by integrity inspection."""

    db_status: IntegrityStatus = Field(..., description="Overall database integrity status")
    fts_healthy: bool = Field(default=True, description="Flag indicating FTS index validity")
    issues: list[str] = Field(default_factory=list, description="List of detected anomalies or errors")
    checked_at_epoch: float = Field(..., description="Inspection epoch timestamp")
    table_counts: dict[str, int] = Field(default_factory=dict, description="Row count per table")


class RepairReport(BaseModel):
    """Outcome report for automated repair operations."""

    status: RepairActionStatus = Field(..., description="Overall repair execution status")
    repaired_items: list[str] = Field(default_factory=list, description="List of repaired entities or actions")
    error_details: list[str] = Field(default_factory=list, description="Error messages encountered during repair")
    duration_ms: float = Field(default=0.0, description="Repair duration in milliseconds")


class StalePrunePolicy(BaseModel):
    """Policy rules governing stale memory pruning and decay."""

    stale_days_threshold: int = Field(default=30, ge=1, description="Days without recall before candidate pruning")
    min_recall_count: int = Field(default=0, ge=0, description="Minimum recall count threshold")
    decay_rate: float = Field(default=0.05, gt=0.0, description="Exponential decay rate lambda")
    protect_pinned: bool = Field(default=True, description="Whether to guard pinned entries from pruning")
    dry_run: bool = Field(default=False, description="Simulate pruning without committing modifications")


class PruneSummary(BaseModel):
    """Execution summary of a stale entry pruning operation."""

    evaluated_count: int = Field(default=0, description="Number of entries evaluated")
    archived_count: int = Field(default=0, description="Number of stale entries archived")
    protected_count: int = Field(default=0, description="Number of pinned/active entries protected")
    archived_ids: list[str] = Field(default_factory=list, description="IDs of archived entries")
    duration_ms: float = Field(default=0.0, description="Prune operation duration in milliseconds")


class HealthMetric(BaseModel):
    """High-level health and hygiene metric for memory storage."""

    overall_health_score: float = Field(..., ge=0.0, le=100.0, description="Health score from 0 to 100")
    total_entries: int = Field(default=0, description="Total memory items stored")
    active_entries: int = Field(default=0, description="Active working memory entries")
    stale_entries: int = Field(default=0, description="Stale candidates identified")
    integrity_status: IntegrityStatus = Field(..., description="Current database integrity status")
