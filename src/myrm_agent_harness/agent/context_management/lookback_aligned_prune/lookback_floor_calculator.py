"""Lookback position aligned floor calculator for prompt cache preservation.

[INPUT]
- lookback_prune_types: LookbackAlignedPruneConfig, LookbackFloorResult, ProjectedContentBlock.

[OUTPUT]
- LookbackFloorCalculator: Calculates the earliest message and content block index
  that cannot be mutated or pruned without breaking active prompt cache prefixes.

[POS]
- Sub-package: myrm_agent_harness.agent.context_management.lookback_aligned_prune
- Module: lookback_floor_calculator.py
"""

from typing import Optional, Sequence

from myrm_agent_harness.agent.context_management.lookback_aligned_prune.lookback_prune_types import (
    LookbackAlignedPruneConfig,
    LookbackFloorResult,
    ProjectedContentBlock,
)


class LookbackFloorCalculator:
    """Calculates the immutable prompt cache boundary based on provider emitted block positions."""

    def __init__(self, config: Optional[LookbackAlignedPruneConfig] = None) -> None:
        self._config = config or LookbackAlignedPruneConfig()

    def resolve_provider_lookback_limit(self, provider_name: str) -> int:
        """Resolves the lookback position limit for a specific provider (e.g. Anthropic: 20)."""
        clean_name = provider_name.lower().strip()
        return self._config.provider_lookback_overrides.get(
            clean_name,
            self._config.default_lookback_positions,
        )

    def calculate_floor(
        self,
        projected_blocks: Sequence[ProjectedContentBlock],
        provider_name: str = "anthropic",
    ) -> LookbackFloorResult:
        """Determines the earliest block and message index that must remain unpruned.

        Args:
            projected_blocks: List of discrete emitted blocks generated by ProviderBlockProjector.
            provider_name: Target model provider name.

        Returns:
            LookbackFloorResult containing protected boundaries and diagnostic explanation.
        """
        total_blocks = len(projected_blocks)
        if total_blocks == 0:
            return LookbackFloorResult(
                total_projected_blocks=0,
                lookback_window_positions=0,
                reserved_headroom_positions=self._config.reserved_headroom_positions,
                protected_floor_message_index=0,
                protected_floor_block_index=0,
                diagnostic_reason="No projected blocks found; entire conversation safe or empty.",
            )

        lookback_limit = self.resolve_provider_lookback_limit(provider_name)
        headroom = self._config.reserved_headroom_positions

        # The protected trailing window covers up to (lookback_limit + headroom) blocks
        # to ensure that subsequent turn inputs do not push active cache out of window.
        conservative_window = min(total_blocks, lookback_limit + headroom)
        floor_block_idx = max(0, total_blocks - conservative_window)

        # Map block index back to message turn index
        floor_message_idx = projected_blocks[floor_block_idx].message_index

        reason = (
            f"Provider '{provider_name}' lookback limit={lookback_limit} with headroom={headroom}. "
            f"Protected window spans trailing {conservative_window} blocks "
            f"(block index >= {floor_block_idx}, message index >= {floor_message_idx})."
        )

        return LookbackFloorResult(
            total_projected_blocks=total_blocks,
            lookback_window_positions=lookback_limit,
            reserved_headroom_positions=headroom,
            protected_floor_message_index=floor_message_idx,
            protected_floor_block_index=floor_block_idx,
            diagnostic_reason=reason,
        )
