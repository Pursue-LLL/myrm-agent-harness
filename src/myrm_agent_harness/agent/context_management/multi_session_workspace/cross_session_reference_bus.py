"""Cross-session reference bus and inter-session state retrieval channel.

[INPUT]
- workspace_types: CrossSessionArtifactItem, CrossSessionReferenceBundle,
  MultiSessionWorkspaceConfig.

[OUTPUT]
- CrossSessionReferenceBus: Registers peer session conclusions, deliverables,
  and artifacts, generating token-bounded cross-session prompt capsules.

[POS]
- Sub-package: myrm_agent_harness.agent.context_management.multi_session_workspace
- Module: cross_session_reference_bus.py
"""

import hashlib
import time
from typing import Dict, List, Optional, Sequence

from myrm_agent_harness.agent.context_management.multi_session_workspace.workspace_types import (
    CrossSessionArtifactItem,
    CrossSessionReferenceBundle,
    MultiSessionWorkspaceConfig,
)


class CrossSessionReferenceBus:
    """Bridges isolated session silos by enabling structured state and artifact extraction."""

    def __init__(self, config: Optional[MultiSessionWorkspaceConfig] = None) -> None:
        self._config = config or MultiSessionWorkspaceConfig()
        self._session_titles: Dict[str, str] = {}
        self._session_summaries: Dict[str, str] = {}
        self._session_artifacts: Dict[str, List[CrossSessionArtifactItem]] = {}

    def register_session_state(
        self,
        session_id: str,
        session_title: str,
        key_findings_summary: str,
        artifacts: Optional[Sequence[CrossSessionArtifactItem]] = None,
    ) -> None:
        """Registers a session's high-level summary and deliverables for peer discovery.

        Args:
            session_id: Source session identifier.
            session_title: Human-readable topic or title.
            key_findings_summary: Distilled conclusion or results.
            artifacts: Optional list of artifacts generated by this session.
        """
        self._session_titles[session_id] = session_title
        self._session_summaries[session_id] = key_findings_summary
        if artifacts:
            self._session_artifacts[session_id] = list(artifacts)
        elif session_id not in self._session_artifacts:
            self._session_artifacts[session_id] = []

    def attach_artifact(
        self,
        session_id: str,
        artifact: CrossSessionArtifactItem,
    ) -> None:
        """Attaches a single artifact to a session record."""
        if session_id not in self._session_artifacts:
            self._session_artifacts[session_id] = []
        self._session_artifacts[session_id].append(artifact)

    def extract_reference_bundle(
        self,
        source_session_id: str,
        target_session_id: str,
    ) -> CrossSessionReferenceBundle:
        """Extracts a peer session's summary and artifacts into a structured reference bundle.

        Args:
            source_session_id: Session from which context is retrieved.
            target_session_id: Session into which context is to be injected.

        Returns:
            CrossSessionReferenceBundle containing verified summary and artifact descriptors.
        """
        title = self._session_titles.get(source_session_id, f"Session {source_session_id[:8]}")
        summary = self._session_summaries.get(
            source_session_id,
            "No prior summary registered for this session.",
        )
        artifacts = tuple(self._session_artifacts.get(source_session_id, []))

        # Generate unique verification digest
        digest_input = f"{source_session_id}->{target_session_id}:{summary}:{len(artifacts)}"
        digest = hashlib.sha256(digest_input.encode("utf-8")).hexdigest()[:16]

        return CrossSessionReferenceBundle(
            source_session_id=source_session_id,
            target_session_id=target_session_id,
            session_title=title,
            key_findings_summary=summary,
            salvaged_artifacts=artifacts,
            reference_digest=digest,
        )

    def render_cross_session_prompt(self, bundle: CrossSessionReferenceBundle) -> str:
        """Renders an prompt block embedding the referenced session's conclusions.

        Args:
            bundle: CrossSessionReferenceBundle to format.

        Returns:
            Structured Markdown string suitable for system or user turn injection.
        """
        lines: List[str] = [
            f"[CROSS_SESSION_CONTEXT source_id=\"{bundle.source_session_id}\" digest=\"{bundle.reference_digest}\"]",
            f"### Referenced Peer Session: {bundle.session_title}",
            f"**Key Findings & Conclusions**:\n{bundle.key_findings_summary}",
        ]

        if bundle.salvaged_artifacts:
            lines.append("\n**Referenced Deliverables & Artifacts**:")
            for item in bundle.salvaged_artifacts:
                uri_desc = f" ({item.uri})" if item.uri else ""
                lines.append(f"- **{item.name}** [{item.mime_type}]{uri_desc}: {item.summary_preview}")

        lines.append("[/CROSS_SESSION_CONTEXT]")
        return "\n".join(lines)
