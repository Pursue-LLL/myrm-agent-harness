"""Server run reservation probe and runtime state verifier.

[INPUT]
- silent_end_types: ReconcileOutcome, ReconcileVerdict, ServerRunReservation,
  SilentEndReconcileConfig, SilentEndTicket, StreamRunStatus.

[OUTPUT]
- ServerRuntimeVerifier: Verifies active server topic reservations to determine
  whether a silent-ended stream has completed, aborted, or is still running in background.

[POS]
- Sub-package: myrm_agent_harness.agent.context_management.silent_end_reconcile
- Module: server_runtime_verifier.py
"""

import time
from typing import Dict, Optional

from myrm_agent_harness.agent.context_management.silent_end_reconcile.silent_end_types import (
    ReconcileOutcome,
    ReconcileVerdict,
    ServerRunReservation,
    SilentEndReconcileConfig,
    SilentEndTicket,
    StreamRunStatus,
)


class ServerRuntimeVerifier:
    """Queries server-side run reservations to safely settle client operations without lock-in."""

    def __init__(self, config: Optional[SilentEndReconcileConfig] = None) -> None:
        self._config = config or SilentEndReconcileConfig()
        self._server_registry: Dict[str, ServerRunReservation] = {}

    def register_server_reservation(self, reservation: ServerRunReservation) -> None:
        """Registers or updates a server-side active operation state for testing or simulation."""
        key = self._format_key(reservation.session_id, reservation.run_id)
        self._server_registry[key] = reservation

    def query_server_reservation(self, session_id: str, run_id: str) -> Optional[ServerRunReservation]:
        """Queries the server reservation registry for the active status of an agent run."""
        key = self._format_key(session_id, run_id)
        return self._server_registry.get(key)

    def reconcile_silent_end(self, ticket: SilentEndTicket) -> ReconcileOutcome:
        """Reconciles a silent-ended stream against server truth to decide local state retirement.

        Args:
            ticket: SilentEndTicket generated by the stream watchdog.

        Returns:
            ReconcileOutcome prescribing whether to retire, resume, or abort the local turn.
        """
        reservation = self.query_server_reservation(ticket.session_id, ticket.run_id)

        # 1. No active reservation found on server -> treat as expired or already terminated
        if reservation is None:
            guidance = (
                f"Server topic reservation for run '{ticket.run_id}' not found. "
                "Retiring local operation to unblock user interface."
            )
            return ReconcileOutcome(
                ticket=ticket,
                verdict=ReconcileVerdict.UNRECOVERABLE_ABORT,
                server_reservation=None,
                should_clear_loading_state=True,
                recovery_guidance=guidance,
            )

        # 2. Server confirms run completed cleanly
        if reservation.status == StreamRunStatus.COMPLETED_ARCHIVED:
            guidance = (
                f"Server confirms run '{ticket.run_id}' completed successfully with output digest. "
                "Settling local stream and releasing loading status."
            )
            return ReconcileOutcome(
                ticket=ticket,
                verdict=ReconcileVerdict.CONFIRMED_TERMINATED,
                server_reservation=reservation,
                should_clear_loading_state=True,
                recovery_guidance=guidance,
            )

        # 3. Server confirms run failed/aborted
        if reservation.status == StreamRunStatus.FAILED_ABORTED:
            diag = reservation.error_diagnostic or "Server terminated execution due to an internal fault."
            guidance = f"Server confirms run '{ticket.run_id}' failed: {diag}. Retiring local operation."
            return ReconcileOutcome(
                ticket=ticket,
                verdict=ReconcileVerdict.CONFIRMED_TERMINATED,
                server_reservation=reservation,
                should_clear_loading_state=True,
                recovery_guidance=guidance,
            )

        # 4. Server confirms run is still actively processing -> recommend reconnection
        if reservation.status == StreamRunStatus.ACTIVE_PROCESSING:
            guidance = (
                f"Server run '{ticket.run_id}' is actively executing in background. "
                "Triggering attach/reconnection stream to resume incremental delivery."
            )
            return ReconcileOutcome(
                ticket=ticket,
                verdict=ReconcileVerdict.STILL_RUNNING_RESUME,
                server_reservation=reservation,
                should_clear_loading_state=False,
                recovery_guidance=guidance,
            )

        # 5. Unknown or expired reservation
        return ReconcileOutcome(
            ticket=ticket,
            verdict=ReconcileVerdict.UNRECOVERABLE_ABORT,
            server_reservation=reservation,
            should_clear_loading_state=True,
            recovery_guidance=f"Unknown server status '{reservation.status}'. Retiring local turn.",
        )

    @staticmethod
    def _format_key(session_id: str, run_id: str) -> str:
        return f"{session_id}::{run_id}"
