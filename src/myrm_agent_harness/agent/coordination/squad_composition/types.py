"""Strongly-typed data contracts for Orchestrator Auto Squad Composition & Budgeting (Item 34).

Defines SquadRoleTier, StopCondition, MemberBlueprint, SquadBlueprint,
ModelDeferredChoice, and MaterializedSquad.

[INPUT]
- __future__
- enum
- dataclasses
- datetime

[OUTPUT]
- SquadRoleTier
- StopCondition
- MemberBlueprint
- SquadBlueprint
- ModelDeferredChoice
- MaterializedMember
- MaterializedSquad

[POS]
Strongly-typed data contracts for Orchestrator Auto Squad Composition & Budgeting (Item 34).
"""

from __future__ import annotations

import enum
from dataclasses import dataclass, field
from datetime import UTC, datetime


class SquadRoleTier(enum.StrEnum):
    """Execution specialization and capability tier for squad members."""

    ORCHESTRATOR = "orchestrator"
    CODER = "coder"
    REVIEWER = "reviewer"
    RESEARCHER = "researcher"
    SPECIALIST = "specialist"


@dataclass(frozen=True)
class StopCondition:
    """Bounded stopping criteria and fan-out protection for an individual role."""

    max_turns: int = 10
    max_tool_calls: int = 30
    allow_failure: bool = False


@dataclass(frozen=True)
class MemberBlueprint:
    """Pre-materialized role blueprint generated by the orchestrator in Phase 1."""

    role_key: str
    display_name: str
    handle: str
    role_tier: SquadRoleTier
    role_description: str
    soul_system_prompt: str
    required_tools: tuple[str, ...] = ()
    required_skills: tuple[str, ...] = ()
    budget_tokens: int = 30000
    max_cost_usd: float = 0.50
    stop_condition: StopCondition = field(default_factory=StopCondition)
    suggested_model_tier: str = "balanced"


@dataclass(frozen=True)
class SquadBlueprint:
    """Complete multi-agent team composition blueprint produced from high-level goal."""

    squad_id: str
    goal_description: str
    members: tuple[MemberBlueprint, ...]
    total_budget_tokens: int
    total_max_cost_usd: float
    max_descendants_per_run: int = 8
    created_at: datetime = field(default_factory=lambda: datetime.now(tz=UTC))


@dataclass(frozen=True)
class ModelDeferredChoice:
    """User-confirmed model selection for a role in Phase 2 of the wizard."""

    role_key: str
    selected_model_id: str
    custom_instructions: str = ""


@dataclass(frozen=True)
class MaterializedMember:
    """Fully instantiated and model-bound squad colleague workstation."""

    role_key: str
    bot_id: str
    handle: str
    display_name: str
    role_tier: SquadRoleTier
    selected_model_id: str
    allocated_budget_tokens: int
    allocated_max_cost_usd: float
    system_prompt: str
    tools: tuple[str, ...]
    skills: tuple[str, ...]
    stop_condition: StopCondition


@dataclass(frozen=True)
class MaterializedSquad:
    """Materialized multi-agent squad ready for autonomous coordinated execution."""

    squad_id: str
    orchestrator_bot_id: str
    members: tuple[MaterializedMember, ...]
    total_budget_tokens: int
    total_max_cost_usd: float
    status: str = "active"
    created_at: datetime = field(default_factory=lambda: datetime.now(tz=UTC))
