"""[INPUT] Pydantic models and enums for subagent report delivery and ordered settlement FIFO.
[OUTPUT] Strong types: ReportDeliveryMode, PermissionMode, FifoItemType, SubagentReportItem, SettlementNoticeItem, OrderedFifoQueueEnvelope, NamedSubagentInstanceConfig.
[POS] Core data types for Subagent report delivery wakeup and FIFO settlement ordering.
"""

from __future__ import annotations

import time
import uuid
from enum import StrEnum

from pydantic import BaseModel, Field


class ReportDeliveryMode(StrEnum):
    """Subagent report delivery strategy."""

    QUIET = "quiet"
    NEXT_STEP = "next-step"


class PermissionMode(StrEnum):
    """Unattended execution permission policy for named subagents."""

    NEVER = "never"
    APPROVE_FOR_ME = "approve-for-me"
    DANGEROUSLY_BYPASS_APPROVALS_AND_SANDBOX = "dangerously-bypass-approvals-and-sandbox"


class FifoItemType(StrEnum):
    """Classification of queued items in the next-step pipeline."""

    REPORT = "report"
    SETTLEMENT = "settlement"


class SubagentReportItem(BaseModel):
    """Active progress report emitted by a subagent during step execution."""

    report_id: str = Field(default_factory=lambda: f"rep_{uuid.uuid4().hex[:10]}")
    subagent_id: str = Field(..., description="Unique subagent instance name or ID")
    task_id: str = Field(..., description="Target subtask identifier")
    summary: str = Field(..., description="One-line executive summary of progress")
    content: str = Field(default="", description="Detailed report body or findings")
    delivery_mode: ReportDeliveryMode = Field(default=ReportDeliveryMode.NEXT_STEP, description="Delivery mode")
    severity: str = Field(default="normal", description="Report criticality: normal / critical")
    timestamp: float = Field(default_factory=time.time, description="Epoch timestamp")
    metadata: dict[str, str] = Field(default_factory=dict, description="Custom operational tags")


class SettlementNoticeItem(BaseModel):
    """Automated settlement notice produced upon subagent run termination."""

    settlement_id: str = Field(default_factory=lambda: f"stl_{uuid.uuid4().hex[:10]}")
    subagent_id: str = Field(..., description="Subagent instance identifier")
    task_id: str = Field(..., description="Associated subtask identifier")
    exit_code: int = Field(default=0, description="Process or subagent exit code")
    status: str = Field(default="completed", description="Settlement state (completed/failed/canceled)")
    summary: str = Field(..., description="Automated settlement summary generated by runtime")
    timestamp: float = Field(default_factory=time.time, description="Epoch timestamp")


class OrderedFifoQueueEnvelope(BaseModel):
    """Strictly ordered queue envelope enforcing Report-before-Settlement FIFO."""

    sequence_id: int = Field(..., description="Monotonically increasing sequence number")
    item_type: FifoItemType = Field(..., description="Payload type: report or settlement")
    task_id: str = Field(..., description="Task identifier for grouping")
    subagent_id: str = Field(..., description="Source subagent instance name")
    wakes_parent: bool = Field(default=False, description="Whether this envelope triggers parent step wakeup")
    urgent_interrupt: bool = Field(default=False, description="Whether this envelope signals urgent parent execution interruption")
    timestamp: float = Field(default_factory=time.time, description="Queue arrival timestamp")
    report_payload: SubagentReportItem | None = Field(default=None, description="Report payload if item_type=report")
    settlement_payload: SettlementNoticeItem | None = Field(default=None, description="Settlement payload if item_type=settlement")


class NamedSubagentInstanceConfig(BaseModel):
    """Configuration for multi-named subagent instance declarations."""

    instance_name: str = Field(..., description="Unique instance name (e.g. codex-worker-alpha)")
    role: str = Field(default="specialist", description="Functional specialty role")
    model_name: str = Field(default="deepseek-chat", description="Underlying model target")
    system_prompt: str = Field(default="", description="Dedicated instance system prompt")
    permission_mode: PermissionMode = Field(default=PermissionMode.APPROVE_FOR_ME, description="Unattended execution mode")
    report_delivery: ReportDeliveryMode = Field(default=ReportDeliveryMode.NEXT_STEP, description="Default report delivery policy")
    tools_allowed: list[str] = Field(default_factory=list, description="Permitted tool identifiers")
